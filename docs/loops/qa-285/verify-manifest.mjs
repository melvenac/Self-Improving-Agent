// QA 285: independent recompute of MANIFEST.json hashes + split/runlist checks. Read-only.
import { createHash } from "node:crypto";
import { readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";
const RUN = "C:/qa-scratch/qa285-run";
const HERE = join(RUN, "docs/loops/jev-calibration-2");
const sha = (p) => createHash("sha256").update(readFileSync(p)).digest("hex");
const m = JSON.parse(readFileSync(join(HERE, "MANIFEST.json"), "utf-8"));
let ok = 0, bad = [];
const chk = (label, path, want) => { const got = sha(path); if (got === want) ok++; else bad.push(`${label}: want ${want} got ${got}`); };
for (const [f, h] of Object.entries(m.hashes.data)) chk(`data ${f}`, join(HERE, f), h);
for (const [f, h] of Object.entries(m.hashes.scripts)) chk(`script ${f}`, join(HERE, f), h);
for (const [f, h] of Object.entries(m.hashes.inputs)) chk(`input ${f}`, join(HERE, f), h);
for (const [f, h] of Object.entries(m.hashes.policies)) chk(`policy ${f}`, join(RUN, f), h);
chk("score_mjs", join(HERE, "score.mjs"), m.hashes.score_mjs);
const onDisk = readdirSync(join(HERE, "inputs")).sort();
const listed = Object.keys(m.hashes.inputs).map((k) => k.slice(7)).sort();
const sameSet = JSON.stringify(onDisk) === JSON.stringify(listed);
console.log(`manifest hashes: ${ok} match, ${bad.length} mismatch`); bad.forEach((b) => console.log("  MISMATCH " + b));
console.log(`input files on disk ${onDisk.length}, in manifest ${listed.length}, same set: ${sameSet}`);
console.log(`counts: data ${Object.keys(m.hashes.data).length}, scripts ${Object.keys(m.hashes.scripts).length}, inputs ${listed.length}, policies ${Object.keys(m.hashes.policies).length}, score_mjs 1`);
const split = JSON.parse(readFileSync(join(RUN, "docs/loops/jev-calibration-2-split.json"), "utf-8"));
const rl = JSON.parse(readFileSync(join(HERE, "runlist.json"), "utf-8"));
const held = rl.phases.heldout.map((r) => r.case_id);
const splitHeld = split.held_out.case_ids;
console.log(`runlist.heldout == split.held_out.case_ids (order and content): ${JSON.stringify(held) === JSON.stringify(splitHeld)} (${held.length} vs ${splitHeld.length})`);
const hs = new Set(splitHeld);
const devHeld = rl.phases.dev.filter((r) => hs.has(r.case_id)).map((r) => r.case_id);
console.log(`dev rows ${rl.phases.dev.length}; dev rows that are held-out ids: ${devHeld.length} ${JSON.stringify(devHeld)}`);
const policies = new Set([...rl.phases.dev, ...rl.phases.heldout].map((r) => r.policy));
console.log(`policies named by runlist rows: ${JSON.stringify([...policies])}; runlist.policy ${rl.policy}`);
const nos = rl.phases.dev.map((r) => r.case_no); console.log(`dev case_no unique: ${new Set(nos).size === nos.length}`);
const allNos = [...rl.phases.dev, ...rl.phases.heldout].map((r) => r.case_no); console.log(`all case_no unique: ${new Set(allNos).size === allNos.length}`);
console.log(`dev labels: ACCEPT ${rl.phases.dev.filter(r=>r.label==="ACCEPT").length}, REJECT ${rl.phases.dev.filter(r=>r.label==="REJECT").length}`);
process.exit(bad.length || !sameSet ? 1 : 0);
