/** Steps 3-9 of bootstrap.md, from a tree whose check says Scaffold. `owner` holds the stand-in's answers. */
async function fromScaffold(install, dir, owner) {
  log(`### Step 3: scaffold\n`);
  const s = OB(dir, "bootstrap", "scaffold");
  expectThat(install, "scaffold exits 0 and verifies with git", s.status === 0 && /Verified with git/.test(s.out));
  const trackedFromScaffold = [...s.out.matchAll(/^\s+tracked\s+\S+\s+(\S+) —/gm)].map((m) => m[1]);
  note(`Scaffold's tracked list (read to the owner): ${trackedFromScaffold.join(", ")}`);

  log(`### Resume check (R-BF-10): a bootstrap interrupted here and resumed at step 1\n`);
  const r = next(install, dir, /Scaffolded, not yet imported: continue at step 4/, "resume at step 4");
  expectThat(install, "check says SCAFFOLDED (not PRE-STATE) and that INBOX is still the template's", /^SCAFFOLDED/.test(agentsLine(r.out)) && /template's/.test(agentsLine(r.out)), agentsLine(r.out));

  log(`### Step 4: CLAUDE.md\n`);
  const claudeState = (r.out.match(/^CLAUDE\.md:\s+(.*)$/m) ?? [, ""])[1];
  const claudePath = join(dir, "CLAUDE.md");
  let claudeChanged = false;
  if (claudeState.startsWith("present, without")) {
    note(`CLAUDE.md is present without the SIA section. Owner (stand-in): "${owner.appendSia ? "yes, append it" : "no"}".`);
    if (owner.appendSia) {
      const existing = readFileSync(claudePath, "utf8");
      const nl = existing.includes("\r\n") ? "\r\n" : "\n";
      writeFileSync(claudePath, existing + (existing.endsWith("\n") ? "" : nl) + nl + SIA_SECTION.replace(/\n/g, nl));
      claudeChanged = true;
    }
  } else if (claudeState === "absent") {
    note(`CLAUDE.md is absent: scanned the project and asked the owner. Owner (stand-in): "${owner.about}". Draft shown, owner: yes.`);
    writeFileSync(claudePath, `# ${owner.title}\n\n**About:** ${owner.about}\n\n## Commands\n\n- build: TBD\n- test: ${owner.test ?? "TBD"}\n- lint: TBD\n\n## Conventions\n\n- Keep changes small.\n- Tests beside the code.\n\n${SIA_SECTION}`);
    claudeChanged = true;
  }
  const c4 = OB(dir, "bootstrap", "check");
  expectThat(install, "after step 4 check still routes to the scaffolded path, never PRE-STATE or 'not a fresh install'", /^SCAFFOLDED/.test(agentsLine(c4.out)) && !/not a fresh install/.test(c4.out));

  log(`### Step 5: INBOX, task.md, SUMMARY title\n`);
  const inbox = join(dir, ".agents/TASKS/INBOX.md");
  const tmpl = readFileSync(inbox, "utf8");
  // Step 5: "Keep the four headings exactly as they are" — read from the scaffolded file, never retyped.
  const heads = tmpl.split(/\r?\n/).filter((l) => /^## \S+ P[0-3] /.test(l));
  expectThat(install, "the scaffolded INBOX has four P0-P3 headings to keep", heads.length === 4, heads.join(" | "));
  const byP = [[], [], [], []];
  for (const t of owner.tasks) byP[t.p].push(`- [ ] ${t.title}`);
  writeFileSync(inbox, `# Inbox\n\n${heads.map((h, i) => `${h}\n\n${byP[i].join("\n")}${byP[i].length ? "\n" : ""}`).join("\n")}`);
  const taskMd = join(dir, ".agents/TASKS/task.md");
  const tm = readFileSync(taskMd, "utf8");
  writeFileSync(taskMd, tm.replace(/(## Current Objective\s*\n)([\s\S]*?)(\n## |$)/, (_m, a, _b, c) => `${a}\n**${owner.objective}**\n${c}`));
  const sumPath = join(dir, ".agents/SYSTEM/SUMMARY.md");
  writeFileSync(sumPath, readFileSync(sumPath, "utf8").replace(/^# .*$/m, `# ${owner.title}`));
  note(`INBOX: ${owner.tasks.length} task(s) under the four headings as they were. task.md: objective "${owner.objective}". SUMMARY: title only (step 5 no longer edits the status line). Shown to the owner.`);

  log(`### Step 6: draft\n`);
  const d = OB(dir, "state", "import", "--draft");
  const tasksLine = (d.out.match(/^Tasks: (\d+)/m) ?? [, "?"])[1];
  expectThat(install, "(a) the draft validates, counts the tasks written, and has no WARNING", d.status === 0 && /^Validates: yes/m.test(d.out) && Number(tasksLine) === owner.tasks.length && !/WARNING/.test(d.out), `Tasks: ${tasksLine}, expected ${owner.tasks.length}`);
  expectThat(install, "the draft's root is this folder", d.out.includes(`Root: ${dir}`));
  if (owner.expectFolderName) expectThat(install, "no package.json: the name is the folder's, and the draft says so", new RegExp(`^Project: ${owner.expectFolderName} — the folder's name`, "m").test(d.out));

  log(`### Step 7: --commit (run by me as the owner's stand-in, in scratch only)\n`);
  const c = OB(dir, "state", "import", "--commit");
  expectThat(install, "--commit writes the record at revision 0", c.status === 0 && /at revision 0/.test(c.out));
  // No record here: say so and stop this install, so the next one still runs (the driver used to throw).
  if (!expectThat(install, "the record exists in THIS folder", existsSync(join(dir, ".agents/state.json")))) return;

  log(`### Step 8: the SIA commit\n`);
  const predicted = new Set([...trackedFromScaffold, ".agents/state.json", ".agents/SESSIONS/next-session.md", ...(claudeChanged ? ["CLAUDE.md"] : [])]);
  note(`Predicted (step 3's tracked list + state.json + next-session.md${claudeChanged ? " + CLAUDE.md" : ""}): ${predicted.size}`);
  const st = G(dir, "status", "--short", "--untracked-files=all");
  const listed = st.out.split("\n").filter(Boolean).map((l) => l.slice(3).replace(/^"|"$/g, ""));
  const extra = listed.filter((p) => !predicted.has(p)), missing = [...predicted].filter((p) => !listed.includes(p));
  expectThat(install, "(d) status lists exactly the predicted paths", extra.length === 0 && missing.length === 0, `listed ${listed.length}, predicted ${predicted.size}${extra.length ? `; extra ${extra.join(", ")}` : ""}${missing.length ? `; missing ${missing.join(", ")}` : ""}`);
  G(dir, "add", "-A");
  G(dir, "commit", "-q", "-m", "Bootstrap SIA");
  const after = G(dir, "status", "--short");
  expectThat(install, "(d) status is empty after the SIA commit", after.out.trim() === "");
  G(dir, "status", "--short", "--ignored");

  log(`### (b) the record\n`);
  const rec = JSON.parse(readFileSync(join(dir, ".agents/state.json"), "utf8"));
  const hist = ["state.json", "TASKS/INBOX.md", "TASKS/task.md", "SESSIONS/next-session.md", "SYSTEM/SUMMARY.md"]
    .map((f) => (readFileSync(join(dir, ".agents", f), "utf8").match(/V-00[1-5]|G-00[1-6]/g) ?? []).length).reduce((a, b) => a + b, 0);
  note(`schema_version ${rec.schema_version}, revision ${rec.revision}, project ${rec.project.name}, tasks ${rec.tasks.map((t) => `${t.id} closed_rev ${t.closed_rev}`).join("; ")}, verified ${rec.verified.length}, gaps ${rec.gaps.length}, decisions ${rec.decisions.length}; SIA-history matches in the 5 files: ${hist}`);
  expectThat(install, "(b) a v3 record with this project's tasks and no SIA history", rec.schema_version === 3 && rec.revision === 0 && rec.tasks.length === owner.tasks.length && hist === 0 && rec.verified.length === 0 && rec.gaps.length === 0);
  if (owner.expectFolderName) expectThat(install, "(b) the record's name is the folder's", rec.project.name === owner.expectFolderName);

  log(`### (c) ob_start (the build's handleStart, called from a script)\n`);
  const s2 = run(process.execPath, ["--input-type=module", "-e",
    `const { handleStart } = await import(${JSON.stringify(pathToFileURL(join(SIA, "open-brain/build/server.js")).href)}); const r = await handleStart({ project_root: ${JSON.stringify(dir)} }); for (const c of r.content) console.log(c.text); if (r.isError) process.exit(1);`],
    dir, `node -e "handleStart({ project_root: '${dir}' })"`);
  expectThat(install, "(c) ob_start renders the record, NOT A SEAT, no problem block", s2.status === 0 && /## State \(state\.json rev 0\)/.test(s2.out) && /NOT A SEAT/.test(s2.out) && !/NO SEAT IDENTITY RESOLVED/.test(s2.out) && new RegExp(`Project: ${rec.project.name}`).test(s2.out));
  const final = OB(dir, "bootstrap", "check");
  expectThat(install, "a final check says BOOTSTRAPPED", /^BOOTSTRAPPED/.test(agentsLine(final.out)));
}

