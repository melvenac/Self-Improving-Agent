// Round 3 acceptance (Forge, record 141): bootstrap.md followed literally in three scratch projects.
//   node docs/loops/dev-scripts-bf-r3/accept-bf-r3.mjs <transcript.md>
// (i) frogger's shape; (ii) an empty folder; (iii) a pyproject.toml project inside a Node parent that has
// .agents/ — the parent must gain nothing — run twice: (iii-a) neither is a repository (QA 135's P7 shape),
// (iii-b) the parent is a repository and the child is its own repository inside it.
// No shell: every command is execFileSync with an args array. Every command, its whole output and its exit
// code go into the transcript. HOME/USERPROFILE and KNOWLEDGE_V2_DB point into the scratch folder, so no real
// home or knowledge DB is read or written. Each `check` is asserted to name the step taken next: a step the
// script took that `Next:` did not name would be a manual fix, and (e) fails.
import { execFileSync, spawnSync } from "node:child_process";
import { mkdirSync, writeFileSync, readFileSync, readdirSync, existsSync, statSync, appendFileSync, mkdtempSync } from "node:fs";
import { join, relative, resolve, dirname } from "node:path";
import { tmpdir } from "node:os";
import { createHash } from "node:crypto";
import { fileURLToPath, pathToFileURL } from "node:url";

const SIA = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");
const CLI = join(SIA, "open-brain", "build", "cli.js");
const OUT = resolve(process.argv[2] ?? join(SIA, "docs/loops/bootstrap-fix-r3-acceptance-transcript.md"));
const SCRATCH = mkdtempSync(join(tmpdir(), "bf-r3-accept-"));
const HOME = join(SCRATCH, "home");
mkdirSync(HOME, { recursive: true });
const ENV = { ...process.env, HOME, USERPROFILE: HOME, KNOWLEDGE_V2_DB: join(HOME, "knowledge-v2.db") };
const GIT_ID = ["-c", "user.name=Forge141", "-c", "user.email=forge141@example.invalid"];

writeFileSync(OUT, `# /bootstrap fix round 3: acceptance transcript (Forge, record 141)\n\n` +
  `Generated by \`docs/loops/dev-scripts-bf-r3/accept-bf-r3.mjs\`. SIA: \`${SIA}\` at ${git(SIA, ["rev-parse", "--short", "HEAD"]).out.trim()} ` +
  `(build stamp: ${readBuildStamp()}). Scratch: \`${SCRATCH}\`. Node ${process.version}, ${process.platform}.\n\n`);
function log(s) { appendFileSync(OUT, s + "\n"); }
function readBuildStamp() { try { return JSON.parse(readFileSync(join(SIA, "open-brain", "build", "build-info.json"), "utf8")).commit ?? "unstamped"; } catch { return "unread"; } }

function run(cmd, args, cwd, label = null) {
  const r = spawnSync(cmd, args, { cwd, encoding: "utf8", env: ENV });
  const out = `${r.stdout ?? ""}${r.stderr ?? ""}`;
  log("```\n$ " + (label ?? `${cmd === process.execPath ? "node" : cmd} ${args.map((a) => (/\s/.test(a) ? JSON.stringify(a) : a)).join(" ")}`) + "\n" + out.replace(/\s+$/, "") + `\n[exit ${r.status}]\n` + "```\n");
  return { status: r.status, out };
}
function OB(cwd, ...args) { return run(process.execPath, [CLI, ...args], cwd, `OB ${args.join(" ")}`); }
function git(cwd, args) { const r = spawnSync("git", args, { cwd, encoding: "utf8" }); return { status: r.status, out: `${r.stdout}${r.stderr}` }; }
function G(cwd, ...args) { return run("git", [...GIT_ID, ...args], cwd, `git ${args.map((a) => (/\s/.test(a) ? JSON.stringify(a) : a)).join(" ")}`); }
function note(s) { log(`> ${s}\n`); }
function write(p, text) { mkdirSync(dirname(p), { recursive: true }); writeFileSync(p, text); }

const verdicts = [];
function expectThat(install, what, ok, detail = "") {
  verdicts.push({ install, what, ok, detail });
  log(`**${ok ? "OK" : "FAIL"}** — ${what}${detail ? `: ${detail}` : ""}\n`);
  return ok;
}
let manualFixes = {};
function next(install, cwd, pattern, stepTaken) {
  const c = OB(cwd, "bootstrap", "check");
  const line = (c.out.match(/^Next:\s+(.*)$/m) ?? [, ""])[1];
  const ok = pattern.test(line);
  expectThat(install, `check's Next names the step taken (${stepTaken})`, ok, ok ? "" : `Next was: ${line}`);
  if (!ok) (manualFixes[install] ??= []).push(stepTaken);
  return c;
}
function agentsLine(out) { return (out.match(/^\.agents\/:\s+(.*)$/m) ?? [, ""])[1]; }

/** Files under a directory with their hashes, skipping `skip` (a child folder). */
function hashTree(dir, skip = null, rel = "") {
  const out = {};
  for (const n of readdirSync(join(dir, rel), { withFileTypes: true })) {
    const r = rel ? `${rel}/${n.name}` : n.name;
    if (skip && join(dir, r) === skip) continue;
    if (n.isDirectory()) Object.assign(out, hashTree(dir, skip, r));
    else out[r] = createHash("sha256").update(readFileSync(join(dir, r))).digest("hex").slice(0, 16);
  }
  return out;
}

