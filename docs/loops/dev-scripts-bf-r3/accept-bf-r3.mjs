// (iii) a pyproject.toml project inside a Node parent that has .agents/
// ---------------------------------------------------------------------------
async function installIII(I, parentIsRepo) {
  const parent = join(SCRATCH, I.replace(/[()]/g, ""), "node-parent");
  const dir = join(parent, "tools", "csvtool");
  log(`## Install ${I}: a pyproject.toml project inside a Node parent that has .agents/ (${parentIsRepo ? "the parent is a repository, the child is its own repository inside it" : "neither is a repository: QA 135's P7 shape"})\n`);
  write(join(parent, "package.json"), JSON.stringify({ name: "node-parent", version: "3.1.4" }, null, 2) + "\n");
  write(join(parent, ".agents/SYSTEM/SUMMARY.md"), "# node-parent\n");
  write(join(parent, ".agents/TASKS/INBOX.md"), "# Inbox\n\n## P1\n\n- [ ] PARENT TASK\n");
  write(join(parent, ".agents/TASKS/task.md"), "# Task\n\n## Current Objective\n\n**The parent's objective**\n");
  write(join(dir, "pyproject.toml"), '[project]\nname = "csvtool"\nversion = "0.3.0"\n');
  write(join(dir, "csvtool/__main__.py"), "# TODO: read stdin\nprint('csv')\n");
  if (parentIsRepo) {
    G(parent, "init", "-q", "-b", "master");
    G(parent, "add", "-A", "--", ".", ":(exclude)tools");
    G(parent, "commit", "-q", "-m", "parent");
    G(dir, "init", "-q", "-b", "master");
    G(dir, "add", "-A");
    G(dir, "commit", "-q", "-m", "csvtool as it was");
    note("The child was already its own repository with a commit (cloned into the parent's folder, say).");
  }
  const before = hashTree(parent, join(parent, "tools"));
  const parentStatusBefore = parentIsRepo ? git(parent, ["status", "--porcelain", "--untracked-files=all"]).out : null;
  note(`The parent before: ${Object.keys(before).length} files (tools/ excluded): ${Object.keys(before).sort().join(", ")}`);
  log(`### Step 1\n`);
  if (!parentIsRepo) {
    next(I, dir, /^git init, then commit the project as it stands/, "2.2 git init + commit");
    log(`### Step 2.2\n`);
    G(dir, "init", "-q", "-b", "master");
    G(dir, "config", "core.autocrlf", "true");
    G(dir, "status", "--short");
    note(`No .gitignore: owner (stand-in): "__pycache__/ and .venv/". Written first.`);
    write(join(dir, ".gitignore"), "__pycache__/\n.venv/\n");
    G(dir, "add", "-A", "--", ".", ":(exclude).agents");
    G(dir, "commit", "-q", "-m", "The project before SIA");
  }
  next(I, dir, /^Scaffold/, "3 scaffold");
  await fromScaffold(I, dir, {
    title: "csvtool", about: "a CSV tool", objective: "csvtool reads stdin", expectFolderName: "csvtool",
    tasks: [{ p: 0, title: "Read stdin" }, { p: 2, title: "Write a README" }],
  });
  log(`### The session-end hook's resolver and sync's (R-BF-9's sibling)\n`);
  const rr = run(process.execPath, ["--input-type=module", "-e",
    `const m = await import(${JSON.stringify(pathToFileURL(join(SIA, "open-brain/build/shared/repo-root.js")).href)}); console.log("resolveHookProjectDir:", m.resolveHookProjectDir(${JSON.stringify(dir)})); console.log("resolveRepoRoot from csvtool/:", m.resolveRepoRoot(${JSON.stringify(join(dir, "csvtool"))}));`],
    dir, "node -e \"resolveHookProjectDir(child); resolveRepoRoot(child/csvtool)\"");
  expectThat(I, "the session-end hook and sync resolve to the child, not the parent", rr.out.split("\n").filter((l) => /^resolve/.test(l)).every((l) => l.endsWith(dir)));
  const after = hashTree(parent, join(parent, "tools"));
  const changed = [...new Set([...Object.keys(before), ...Object.keys(after)])].filter((k) => before[k] !== after[k]);
  expectThat(I, "the parent gained nothing: every file outside tools/ has the same bytes, and there is no new one", changed.length === 0, changed.length ? `changed or new: ${changed.join(", ")}` : `${Object.keys(after).length} files, identical`);
  if (parentIsRepo) {
    const parentStatusAfter = git(parent, ["status", "--porcelain", "--untracked-files=all"]).out;
    expectThat(I, "the parent's git status is what it was", parentStatusAfter === parentStatusBefore, parentStatusAfter.trim() || "(empty)");
  }
}
