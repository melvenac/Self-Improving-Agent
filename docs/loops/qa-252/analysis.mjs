#!/usr/bin/env node
// QA 252: supplementary tables for the Jev calibration 1 report, generated from the records, labels.json and
// sample.json. It does NOT replace score.mjs (which is the frozen method of record and is not edited); it adds
// (1) the per-question answer distribution by label, (2) per-question ranking power (AUC, label ACCEPT positive,
// on p = P(diff acceptable) as score.mjs defines it), (3) the single-question threshold that maximises balanced
// accuracy ON THIS SET (fitted; needs a held-out set), (4) the reasons the gate recorded, verbatim-normalised.
// No network call, no key, no policy file read or written.
// Usage: node docs/loops/qa-252/analysis.mjs   (writes docs/loops/jev-calibration-1/results/qa252-analysis.md)
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const ROOT = "C:/qa-scratch/qa252-wt/docs/loops/jev-calibration-1";
const labels = JSON.parse(readFileSync(`${ROOT}/labels.json`, "utf8"));
const sample = JSON.parse(readFileSync(`${ROOT}/sample.json`, "utf8"));
const byNo = new Map(labels.map((l) => [l.case_no, l]));
const recs = readdirSync(`${ROOT}/records`).filter((f) => /\.G_done\..*\.json$/.test(f))
  .map((f) => JSON.parse(readFileSync(`${ROOT}/records/${f}`, "utf8")))
  .filter((r) => r.outcome_class === "answered");

const Q = {
  diff_matches_plan: (a) => a.noul,
  touches_out_of_scope: (a) => 1 - a.noul,
  local_tests_support_claim: (a) => a.noul,
  stuck_repeating_prior_failure: (a) => 1 - a.noul,
  risk_of_regression: (a) => 1 - a.score / 2,
};
const RAW = { diff_matches_plan: "noul", touches_out_of_scope: "noul", local_tests_support_claim: "noul", stuck_repeating_prior_failure: "noul", risk_of_regression: "score" };

const rows = recs.map((r) => {
  const l = byNo.get(r.pr);
  const group = sample.headline.includes(l.case_id) ? "headline" : sample.leak_group.includes(l.case_id) ? "leak_group" : null;
  return { case_id: l.case_id, label: l.label, group, answer: r.answer, reasons: r.decision.reasons, tokens: r.usage.input_tokens + r.usage.output_tokens };
}).filter((r) => r.group);

const r3 = (x) => (x === null || Number.isNaN(x) ? "n/a" : x.toFixed(3));
const mean = (xs) => (xs.length ? xs.reduce((s, x) => s + x, 0) / xs.length : null);
function auc(pos, neg) {
  if (!pos.length || !neg.length) return null;
  let s = 0;
  for (const p of pos) for (const n of neg) s += p > n ? 1 : p === n ? 0.5 : 0;
  return s / (pos.length * neg.length);
}
function bestThreshold(pos, neg) {
  const cuts = [...new Set([...pos, ...neg])].sort((a, b) => a - b);
  let best = null;
  for (const t of cuts) {
    const tpr = pos.filter((p) => p >= t).length / pos.length;
    const tnr = neg.filter((n) => n < t).length / neg.length;
    const ba = (tpr + tnr) / 2;
    if (!best || ba > best.ba) best = { t, ba, tpr, tnr };
  }
  return best;
}

const out = ["# Jev calibration 1: supplementary tables (generated by docs/loops/qa-252/analysis.mjs; do not hand-edit)", "",
  "p = P(diff acceptable) per question, as score.mjs defines it. AUC: the chance a random ACCEPT case gets a higher p than a",
  "random REJECT case (0.5 = no ranking power). The best cut is the p threshold (proceed at p >= cut) that maximises",
  "balanced accuracy for that one question ON THIS SET: **fitted to this set; needs a held-out set**.", ""];

for (const [name, set] of [["Headline", rows.filter((r) => r.group === "headline")], ["Leak-wording group", rows.filter((r) => r.group === "leak_group")], ["All scored", rows]]) {
  const A = set.filter((r) => r.label === "ACCEPT");
  const R = set.filter((r) => r.label === "REJECT");
  out.push(`## ${name} (N = ${set.length}: ${A.length} ACCEPT, ${R.length} REJECT)`, "",
    "| question | raw field | mean raw, ACCEPT | mean raw, REJECT | min-max raw, all | AUC | best cut on p (fitted) | balanced acc. at cut | ACCEPT proceed / REJECT reject at cut |",
    "|---|---|---|---|---|---|---|---|---|");
  for (const [q, f] of Object.entries(Q)) {
    const raw = (r) => r.answer[q][RAW[q]];
    const pa = A.map((r) => f(r.answer[q]));
    const pr = R.map((r) => f(r.answer[q]));
    const all = set.map(raw);
    const b = bestThreshold(pa, pr);
    out.push(`| ${q} | ${RAW[q]} | ${r3(mean(A.map(raw)))} | ${r3(mean(R.map(raw)))} | ${r3(Math.min(...all))}-${r3(Math.max(...all))} | ${r3(auc(pa, pr))} | ${b ? r3(b.t) : "n/a"} | ${b ? r3(b.ba) : "n/a"} | ${b ? `${r3(b.tpr)} / ${r3(b.tnr)}` : "n/a"} |`);
  }
  out.push("");
}

// The thresholds the gate applied, against what Jev answered: how many cases clear each one.
const policy = recs[0].decision.applied;
out.push("## How many cases clear each applied threshold (all scored, N = " + rows.length + ")", "",
  `Applied (from the records, policy_hash ${recs[0].policy_hash.slice(0, 12)}): ${JSON.stringify(policy)}`, "",
  "| rule | ACCEPT cases clearing it | REJECT cases clearing it |", "|---|---|---|");
const A = rows.filter((r) => r.label === "ACCEPT");
const R = rows.filter((r) => r.label === "REJECT");
const rules = [
  ["diff_matches_plan >= " + policy.diff_matches_plan_min, (a) => a.diff_matches_plan.noul >= policy.diff_matches_plan_min],
  ["touches_out_of_scope <= " + policy.touches_out_of_scope_max, (a) => a.touches_out_of_scope.noul <= policy.touches_out_of_scope_max],
  ["local_tests_support_claim >= " + policy.local_tests_support_claim_min, (a) => a.local_tests_support_claim.noul >= policy.local_tests_support_claim_min],
  ["stuck_repeating_prior_failure <= " + policy.stuck_repeating_prior_failure_max, (a) => a.stuck_repeating_prior_failure.noul <= policy.stuck_repeating_prior_failure_max],
  ["risk_of_regression < " + policy.risk_of_regression_rollback_at_or_above, (a) => a.risk_of_regression.score < policy.risk_of_regression_rollback_at_or_above],
];
for (const [name, ok] of rules) out.push(`| ${name} | ${A.filter((r) => ok(r.answer)).length} of ${A.length} | ${R.filter((r) => ok(r.answer)).length} of ${R.length} |`);
out.push("");

// A combined gate at the two driving cuts FITTED ON THE HEADLINE, with every other applied rule unchanged and checks
// set aside (as (b) does). Fitted on the headline, so the headline row is optimistic; the leak group is NOT a held-out
// set (different text, same pool), only a second look.
const H = rows.filter((r) => r.group === "headline");
const cut = (q) => bestThreshold(H.filter((r) => r.label === "ACCEPT").map((r) => Q[q](r.answer[q])), H.filter((r) => r.label === "REJECT").map((r) => Q[q](r.answer[q]))).t;
const dmpCut = cut("diff_matches_plan");
const ltCut = cut("local_tests_support_claim");
const fitted = (a) => a.diff_matches_plan.noul >= dmpCut && a.local_tests_support_claim.noul >= ltCut &&
  a.touches_out_of_scope.noul <= policy.touches_out_of_scope_max && a.stuck_repeating_prior_failure.noul <= policy.stuck_repeating_prior_failure_max &&
  a.risk_of_regression.score < policy.risk_of_regression_rollback_at_or_above;
out.push("## A combined gate at cuts fitted on the headline (FITTED TO THIS SET; NEEDS A HELD-OUT SET)", "",
  `diff_matches_plan >= ${dmpCut} and local_tests_support_claim >= ${ltCut} (both fitted on the headline), other rules as applied, checks set aside.`, "",
  "| group | n | ACCEPT proceed | REJECT reject | balanced accuracy | false-accept rate |", "|---|---|---|---|---|---|");
for (const [name, set] of [["Headline (fitted here)", H], ["Leak-wording group (not held out)", rows.filter((r) => r.group === "leak_group")], ["All scored", rows]]) {
  const a = set.filter((r) => r.label === "ACCEPT");
  const rj = set.filter((r) => r.label === "REJECT");
  const ap = a.filter((r) => fitted(r.answer)).length / a.length;
  const rr = rj.filter((r) => !fitted(r.answer)).length / rj.length;
  out.push(`| ${name} | ${set.length} | ${a.filter((r) => fitted(r.answer)).length} of ${a.length} | ${rj.filter((r) => !fitted(r.answer)).length} of ${rj.length} | ${r3((ap + rr) / 2)} | ${r3(1 - rr)} |`);
}
out.push("");

// Every confident miss over ALL five questions, from score.mjs's own scores.json (its scores.md lists the driving
// questions only, and there are none there).
const scores = JSON.parse(readFileSync(`${ROOT}/results/scores.json`, "utf8"));
for (const [name, g] of [["headline", scores.headline], ["leak_group", scores.leak_group]]) {
  const cm = g.calibration_all_questions.confident_misses;
  const byQ = {};
  for (const m of cm) byQ[m.question] = (byQ[m.question] ?? 0) + 1;
  out.push(`## Confident misses over all five questions, ${name} (from scores.json): ${cm.length}`, "", `By question: ${JSON.stringify(byQ)}`, "",
    "| case | question | p | said | label |", "|---|---|---|---|---|", ...cm.map((m) => `| ${m.case_id} | ${m.question} | ${m.p} | ${m.stance} | ${m.label} |`), "");
}

const reasons = {};
for (const r of rows) for (const x of r.reasons) { const k = x.replace(/\d+(\.\d+)?/g, "#"); reasons[k] = (reasons[k] ?? 0) + 1; }
out.push("## Reasons the gate recorded (all scored; numbers replaced by #)", "", "| reason | records |", "|---|---|",
  ...Object.entries(reasons).sort((a, b) => b[1] - a[1]).map(([k, n]) => `| ${k} | ${n} |`), "");

out.push("## Per case (all scored)", "", "| case | group | label | diff_matches_plan | touches_out_of_scope | local_tests_support_claim | stuck_repeating_prior_failure | risk_of_regression | tokens |", "|---|---|---|---|---|---|---|---|---|");
for (const r of [...rows].sort((a, b) => a.group.localeCompare(b.group) || a.label.localeCompare(b.label) || a.case_id.localeCompare(b.case_id))) {
  const a = r.answer;
  out.push(`| ${r.case_id} | ${r.group} | ${r.label} | ${a.diff_matches_plan.noul} | ${a.touches_out_of_scope.noul} | ${a.local_tests_support_claim.noul} | ${a.stuck_repeating_prior_failure.noul} | ${a.risk_of_regression.score} | ${r.tokens} |`);
}
out.push("");
writeFileSync(`${ROOT}/results/qa252-analysis.md`, out.join("\n"));
console.log(`wrote ${ROOT}/results/qa252-analysis.md from ${rows.length} answered record(s)`);
