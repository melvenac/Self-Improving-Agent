// QA 287: independent manifest recompute + split check (read-only). Run from the run tree root.
import { readFileSync, readdirSync } from "node:fs";
import { createHash } from "node:crypto";
const H = "docs/loops/jev-calibration-2/";
const sha = (p) => createHash("sha256").update(readFileSync(p)).digest("hex");
const m = JSON.parse(readFileSync(H + "MANIFEST.json", "utf8"));
let ok = 0;
const bad = [];
const chk = (p, want) => (sha(p) === want ? ok++ : bad.push(p));
for (const [k, v] of Object.entries(m.hashes.scripts)) chk(H + k, v);
for (const [k, v] of Object.entries(m.hashes.data)) chk(H + k, v);
for (const [k, v] of Object.entries(m.hashes.inputs)) chk(H + k, v);
for (const [k, v] of Object.entries(m.hashes.policies)) chk(k, v);
chk(H + "score.mjs", m.hashes.score_mjs);
const onDisk = readdirSync(H + "inputs").sort();
const inMan = Object.keys(m.hashes.inputs).map((k) => k.slice(7)).sort();
console.log(`manifest hashes: ${ok} match, ${bad.length} mismatch ${bad.join(",")}`);
console.log(`input files on disk ${onDisk.length}, in manifest ${inMan.length}, same set: ${JSON.stringify(onDisk) === JSON.stringify(inMan)}`);
const split = JSON.parse(readFileSync("docs/loops/jev-calibration-2-split.json", "utf8"));
const rl = JSON.parse(readFileSync(H + "runlist.json", "utf8"));
const ho = rl.phases.heldout.map((r) => r.case_id);
console.log(`heldout runlist ${ho.length} v split ${split.held_out.case_ids.length}; equal in order: ${JSON.stringify(ho) === JSON.stringify(split.held_out.case_ids)}`);
const hs = new Set(split.held_out.case_ids);
const dev = rl.phases.dev;
console.log(`dev rows ${dev.length}; dev rows that are held-out ids: ${dev.filter((r) => hs.has(r.case_id)).length}`);
console.log(`dev labels: ACCEPT ${dev.filter((r) => r.label === "ACCEPT").length}, REJECT ${dev.filter((r) => r.label === "REJECT").length}`);
console.log(`policies named: ${[...new Set([...dev, ...rl.phases.heldout].map((r) => r.policy))].join(", ")}`);
const nos = [...dev, ...rl.phases.heldout].map((r) => r.case_no);
console.log(`case_no unique over ${nos.length} rows: ${new Set(nos).size === nos.length}`);
